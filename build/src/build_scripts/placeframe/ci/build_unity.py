from __future__ import annotations

import hashlib
import shutil
import tempfile
from pathlib import Path
from typing import NotRequired, TypedDict

import typer
from common.bash import bash
from pydantic_settings import BaseSettings

from ...shared.cache import restore, save
from ...shared.check_tracked_files import check_tracked_files
from ...shared.ci_step import ci_step
from ...shared.license_restore import restore_license
from ...shared.setup import configure_git, free_disk_space, install_dotnet
from ...shared.setup_oras import install_oras
from ..projects import load_unity_projects
from ..unity_batch_mode_command import unity_batchmode_command


class Settings(BaseSettings):
    github_workspace: str


settings = Settings.model_validate({})


class PlatformConfig(TypedDict):
    build_flag: str
    build_target: NotRequired[str]
    module: str


PLATFORM_CONFIGS: dict[str, PlatformConfig] = {
    "android-mobile": {"build_flag": "-buildTarget Android", "build_target": "Android", "module": "android"},
    "magicleap": {"build_flag": "-buildTarget Android", "build_target": "Android", "module": "android"},
    "linux64": {"build_flag": "-buildLinux64Player", "module": "linux-il2cpp"},
    "win64": {"build_flag": "-buildTarget Win64", "build_target": "Win64", "module": "windows-mono"},
}

app = typer.Typer(add_completion=False, pretty_exceptions_show_locals=False)


@app.command()
def main(
    project: str = typer.Option(help="Project name"),
    project_path: Path = typer.Option(help="Path to Unity project"),
    platform: str = typer.Option(help="Target platform"),
    cache_key: str = typer.Option(help="Cache key prefix"),
    commit_sha: str = typer.Option("dev", help="Git commit SHA"),
    registry: str = typer.Option(help="OCI registry path"),
) -> None:
    with ci_step("Setup"):
        configure_git(settings.github_workspace)
        free_disk_space()
        install_dotnet("8.0")
        install_oras()
        restore_license()

    with ci_step("Restore packages"):
        bash("dotnet tool restore")
        bash(f"dotnet nugetforunity restore {project_path}")
        manifest = project_path / "Packages" / "manifest.json"
        tag = f"{cache_key}-{platform}-{hashlib.sha256(manifest.read_bytes()).hexdigest()[:8]}"

    with ci_step("Restore library cache"):
        restore(registry, "unity-library", tag, Path("."))

    with ci_step("Prepare build"):
        config = load_unity_projects()
        if project not in config.projects:
            raise SystemExit(f"Unknown project '{project}'. Valid: {', '.join(config.projects)}")
        if platform not in PLATFORM_CONFIGS:
            raise SystemExit(f"Unknown platform '{platform}'. Valid: {', '.join(PLATFORM_CONFIGS)}")

        project_config = config.projects[project]
        platform_config = PLATFORM_CONFIGS[platform]
        unity_project_path = project_config.path

        build_info_path = unity_project_path / "Assets" / "OuternetClient" / "BuildInfo.generated.cs"
        if build_info_path.parent.exists():
            build_info_path.write_text(
                "// Auto-generated by build pipeline — do not edit\n"
                "namespace Outernet.Client\n"
                "{\n"
                "    public static class BuildInfo\n"
                "    {\n"
                f'        public const string CommitSha = "{commit_sha[:8]}";\n'
                "    }\n"
                "}\n"
            )

    with ci_step(f"Build {unity_project_path.name} [{platform}]"):
        command = unity_batchmode_command(unity_project_path)

        if "build_target" in platform_config:
            execute_method = (project_config.execute_methods or {}).get(platform)
            if not execute_method:
                raise SystemExit(f"No execute method for {unity_project_path.name} [{platform}]")
            command += f" {platform_config['build_flag']} -executeMethod {execute_method}"
        else:
            output_path = (
                Path(tempfile.gettempdir())
                / "unity-builds"
                / unity_project_path.name
                / platform
                / unity_project_path.name
            )
            output_path.parent.mkdir(parents=True, exist_ok=True)
            command += f" {platform_config['build_flag']} {output_path}"

        bash(f"{command} -logFile /dev/stdout")

    with ci_step("Check tracked files"):
        unexpected = check_tracked_files(unity_project_path)
        if unexpected:
            print(f"WARNING: Unexpected tracked-file changes in {unity_project_path.name} were restored:")
            for file in unexpected:
                print(f"  {file}")

    with ci_step("Save library cache"):
        # PackageCache (~1.6 GiB) is redundant with the shared UPM cache at ~/.cache/Unity/upm/
        package_cache = project_path / "Library" / "PackageCache"
        if package_cache.exists():
            shutil.rmtree(package_cache)

        save(registry, "unity-library", tag, Path("."), [f"{project_path}/Library/"])

    with ci_step("Collect build artifacts"):
        build_directory = project_path / "Build"
        if build_directory.is_dir():
            artifact_directory = Path("/tmp/unity-builds")
            artifact_directory.mkdir(parents=True, exist_ok=True)
            shutil.copytree(build_directory, artifact_directory, dirs_exist_ok=True)
