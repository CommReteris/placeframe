from __future__ import annotations

from pathlib import Path

import typer
from common.bash import bash, bash_check

from ...shared.ci_step import ci_step

app = typer.Typer(add_completion=False, pretty_exceptions_show_locals=False)

ENV_LOCK_DIR = Path("/tmp/env-locks")


def _merge_env_locks() -> None:
    if not ENV_LOCK_DIR.is_dir():
        return
    merged: dict[str, str] = {}
    for lock_file in sorted(ENV_LOCK_DIR.glob("*/.env.lock")):
        for line in lock_file.read_text(encoding="utf-8").splitlines():
            if "=" in line and not line.startswith("#"):
                key, value = line.split("=", 1)
                merged[key.strip()] = value.strip()
    if merged:
        Path(".env.lock").write_text(
            "# Generated by lock.py\n" + "\n".join(f"{k}={v}" for k, v in sorted(merged.items())) + "\n",
            encoding="utf-8",
        )


@app.command()
def main() -> None:
    with ci_step("Commit CI artifacts"):
        _merge_env_locks()

        bash('git config user.name "github-actions[bot]"')
        bash('git config user.email "github-actions[bot]@users.noreply.github.com"')
        bash("git add .env.lock build/package-versions.json packages/unity/Placeframe/Assets/Package/*/package.json")

        if not bash_check("git diff --cached --quiet"):
            bash('git commit -m "ci: update locks and versions"')
            bash("git push")
        else:
            print("No CI artifacts to commit")
